const deck = document.querySelector('.shop-deck');
if (deck) {
  const cards = [...deck.querySelectorAll('.shop-deck-card')];
  const switchButtons = [...document.querySelectorAll('.deck-switch [data-show-shop]')];
  let active = location.hash === '#hachioji' ? 1 : 0;
  const sizeDeck = () => { deck.style.height = `${cards[active].offsetHeight}px`; };
  function showShop(index, focus = false, updateHash = false) {
    active = (index + cards.length) % cards.length;
    deck.classList.toggle('is-showing-hachioji', active === 1);
    cards.forEach((card, i) => {
      const isActive = i === active;
      card.classList.toggle('is-front', isActive);
      card.classList.toggle('is-back', !isActive);
      const face = card.querySelector('.deck-face');
      face.inert = !isActive;
      if (isActive) face.removeAttribute('aria-hidden');
      else face.setAttribute('aria-hidden', 'true');
    });
    switchButtons.forEach((button, i) => button.setAttribute('aria-pressed', String(i === active)));
    const live = document.querySelector('.deck-live');
    if (live) live.textContent = language === 'en' ? `${active === 0 ? 'Hino' : 'Hachioji'} shop shown` : `${active === 0 ? '日野店' : '八王子店'}を表示中`;
    const current = document.querySelector('.deck-controls-current');
    if (current) current.textContent = language === 'en' ? (active === 0 ? 'Hino' : 'Hachioji') : (active === 0 ? '日野店' : '八王子店');
    applyJapaneseLineBreaks();
    sizeDeck();
    if (updateHash) history.replaceState(null, '', location.pathname + location.search + '#' + cards[active].id);
    if (focus) cards[active].querySelector('h3')?.focus({ preventScroll: true });
  }
  document.querySelectorAll('[data-show-shop]').forEach((button) => button.addEventListener('click', () => showShop(Number(button.dataset.showShop), true, true)));
  document.querySelectorAll('[data-slide-direction]').forEach((button) => button.addEventListener('click', () => showShop(active + Number(button.dataset.slideDirection), false, true)));
  deck.addEventListener('keydown', (event) => {
    if (event.key !== 'ArrowLeft' && event.key !== 'ArrowRight') return;
    event.preventDefault();
    showShop(active + (event.key === 'ArrowRight' ? 1 : -1), true, true);
  });
  let startPoint = null;
  deck.addEventListener('pointerdown', (event) => {
    startPoint = event.target.closest('a, button') ? null : { x: event.clientX, y: event.clientY };
  });
  deck.addEventListener('pointerup', (event) => {
    if (!startPoint) return;
    const distanceX = event.clientX - startPoint.x;
    const distanceY = event.clientY - startPoint.y;
    if (Math.abs(distanceX) > 65 && Math.abs(distanceX) > Math.abs(distanceY) * 1.25) {
      showShop(active + (distanceX < 0 ? 1 : -1), false, true);
    }
    startPoint = null;
  });
  deck.addEventListener('pointercancel', () => { startPoint = null; });
  window.addEventListener('resize', sizeDeck);
  if (window.ResizeObserver) {
    const deckObserver = new ResizeObserver(sizeDeck);
    cards.forEach((card) => deckObserver.observe(card));
  }
  languageButton?.addEventListener('click', () => requestAnimationFrame(sizeDeck));
  window.addEventListener('hashchange', () => {
    if (location.hash === '#hino' || location.hash === '#hachioji') showShop(location.hash === '#hachioji' ? 1 : 0);
  });
  showShop(active);
}
